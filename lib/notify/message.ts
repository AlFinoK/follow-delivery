// Шаблон уведомления клиенту (§5 ТЗ + правка «Уведомить клиента»).
//
// Текст РУССКИЙ и в i18n не заводится — по той же причине, что и PDF накладной
// (CLAUDE.md §11): это документ для клиента, а не интерфейс оператора. Получатели —
// физлица в РФ, язык интерфейса админки на текст сообщения влиять не должен.
//
// Вариантов текста два, и это принципиально:
//   whatsapp — полный, по образцу заказчика (эмодзи, блок про MAX, предупреждение
//              об оплате). Длина в мессенджере не тарифицируется;
//   sms      — короткий: номер, сумма, телефон. Ссылки нет намеренно, см. smsText().

import { COMPANY, trackUrl } from '@/lib/waybill/company'
// Импорт из totals.ts, а НЕ из model.ts: model.ts тянет react-phone-number-input,
// который ломает вычисление модуля в серверном рантайме (см. totals.ts).
import { fmtMoney } from '@/lib/waybill/totals'
import type { Waybill } from '@/lib/waybill/model'
import type { NotifyChannel } from './types'

/**
 * Телефон отдела доставки в виде «+7 708 703 7711».
 *
 * Берём из COMPANY, а не строкой в шаблоне: company.ts — единственное место правки
 * реквизитов, иначе номер в уведомлении и в PDF со временем разойдутся. В COMPANY он
 * записан как «8 708 703 77 11», поэтому приводим к международному виду.
 */
function contactPhone(): string {
	const dept = COMPANY.departments.find((d) => d.title.includes('доставки')) ?? COMPANY.departments[0]
	const digits = (dept?.phone ?? '').replace(/\D/g, '').slice(-10)
	return digits.length === 10 ? `+7 ${digits.slice(0, 3)} ${digits.slice(3, 6)} ${digits.slice(6)}` : (dept?.phone ?? '')
}

/**
 * Полный текст для WhatsApp — по образцу заказчика, включая эмодзи и капслок в
 * предупреждении об оплате. Формулировки менять только по его слову.
 *
 * Подставляются три значения: номер накладной, город доставки и сумма. Блоки с
 * незаполненными полями выпадают целиком — иначе клиент получил бы «К оплате 0 тенге»
 * или пустую строку после «🔹».
 */
function whatsappText(w: Waybill): string {
	const blocks: string[] = [
		`Добрый день!\nВас Уведомляет Транспортная компания Leader Trans Team.`,
		`📲Убедительная просьба добавить меня в MAX для связи: ${contactPhone()}`,
		`✅ Груз принят к отправке.`,
		// Диплинк с номером: страница сама находит груз, клиенту не надо ничего
		// вводить руками. Без номера (черновик) остаётся ссылка на главную.
		`📦 Отслеживание по трек-номеру: ${trackUrl(w.number)}`,
	]

	const track = [
		w.number ? `🔹 Трек-номер (накладная):\n🔹  ${w.number}` : '',
		w.receiver.city.trim() ? `📍 ${w.receiver.city.trim()}` : '',
	].filter(Boolean)
	if (track.length) blocks.push(track.join('\n'))

	blocks.push(`ОПЛАТА ИСКЛЮЧИТЕЛЬНО НА КАРТУ ТРАНСПОРТНОЙ КОМПАНИИ В РУБЛЯХ!!!`)

	if (w.amount) {
		blocks.push(`💰 К оплате при получении:\n${fmtMoney(w.amount)} тенге\n(по курсу валюты на день оплаты)`)
	}

	blocks.push(
		`📌 Реквизиты — перед доставкой.\n🧮 Расчёт стоимости будущих грузов: ${COMPANY.site}\nС уважением, Leader Trans Team`
	)

	return blocks.join('\n\n')
}

/**
 * Короткий текст для SMS — номер накладной, сумма и телефон.
 *
 * ⛔ **Ссылки в SMS НЕТ, и это не упущение.** 2026-09-19 проверено живыми отправками
 * через SMSC с общего имени отправителя `SMSC.KZ`: сообщение без ссылки доставляется
 * за минуту, а со ссылкой навсегда зависает в статусе «Передано оператору» — оператор
 * молча гасит его. Проверены три варианта: полный адрес, он же в одном сегменте и
 * короткая ссылка через `tinyurl=1` на домене самого SMSC. Результат одинаковый, то
 * есть режется ссылка как таковая, а не домен или длина.
 *
 * Поэтому вместо ссылки — телефон отдела доставки: без неё клиенту нужен хоть какой-то
 * способ узнать судьбу груза, а ответить на SMS он не может (отправитель — буквенное
 * имя, а не номер). Ссылка остаётся в WhatsApp, куда уходит основной поток.
 *
 * Это ВРЕМЕННО: ссылку вернём, когда компания зарегистрирует собственное имя
 * отправителя — от своего имени операторы ссылки обычно пропускают.
 *
 * Про длину. Кириллица кодируется UCS-2: 70 символов на одиночное сообщение и 67 на
 * часть составного. Текущий текст с суммой и телефоном укладывается в две части.
 * Отсюда два решения, которые выглядят мелочью, но таковой не являются:
 *   — никаких эмодзи: они намертво удерживают сообщение в UCS-2 и съедают ёмкость;
 *   — «тг» вместо «тенге»: на длинных суммах это ровно разница между 2 и 3 частями.
 *
 * Пустые поля выпадают: при нулевой сумме строки про оплату нет — иначе клиент
 * получил бы «К оплате 0 тг».
 */
function smsText(w: Waybill): string {
	const head = `Leader Trans Team: груз принят.${w.number ? ` Накладная ${w.number}.` : ''}`
	const pay = w.amount ? `К оплате ${fmtMoney(w.amount)} тг.` : ''
	return [head, [pay, `Тел. ${contactPhone()}`].filter(Boolean).join(' ')].join('\n')
}

/** Текст уведомления под конкретный канал. */
export function buildClientMessage(w: Waybill, channel: NotifyChannel): string {
	return channel === 'sms' ? smsText(w) : whatsappText(w)
}

/** Оба варианта сразу — для предпросмотра в модалке и для фолбэка. */
export function buildClientMessages(w: Waybill): Record<NotifyChannel, string> {
	return { whatsapp: whatsappText(w), sms: smsText(w) }
}
